"""Export the data behind the browser demo (docs/index.html).

Writes docs/demo_data.js: the Stage-1 girder and the grillage (crack on G1 or on G3) solved at a
dense grid of eta, with the crack width, the truck deflection, the stiffness ratio along the span
and, for the grillage, the stage-B moment of every girder. The page turns a crack width into eta
and the responses by linear interpolation between these solved points; it runs no FEM itself.
"""
import json
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from crackfem.girder1d import Girder1D  # noqa: E402
from crackfem.grillage import Grillage  # noqa: E402
from crackfem.inverse import eta_decompression  # noqa: E402

N_EL_GRID = 20                      # grillage mesh of run_stage2.py
GIRDERS = {"G1": 0, "G3": 2}
GATE_PX = 3.0                       # the pipeline refuses widths below 3 px
U_PER_GSD = 2.0                     # u = 2·GSD
GSDS_MM = (0.02, 0.05, 0.10)
ETA_MIN = 0.05
N_ETA_STAGE1, N_ETA_GRID = 80, 30
OUT = ROOT / "docs" / "demo_data.js"


def sig(x, digits: int = 6):
    """Round to significant figures (lists element-wise) to keep the page small."""
    if isinstance(x, (list, tuple, np.ndarray)):
        return [sig(v, digits) for v in x]
    return float(f"{float(x):.{digits}g}")


def check_monotone(rows: list, name: str) -> None:
    """Below decompression the width must grow as eta falls, or the page cannot invert it."""
    w = [r["w_mm"] for r in rows[1:]]                  # rows[0] is eta = 1
    if any(b <= a for a, b in zip(w, w[1:])):
        raise RuntimeError(f"{name}: crack width is not increasing as eta falls")


def stage1_model() -> dict:
    g = Girder1D()
    eta_dec = eta_decompression(g.w_pred)
    rows = []
    for eta in [1.0, *np.linspace(eta_dec, ETA_MIN, N_ETA_STAGE1)]:
        ind = g.indicator(float(eta))
        rows.append({"eta": sig(eta), "w_mm": sig(ind["w_pred_mm"]),
                     "defl_mm": sig(ind["deflection_truck_mm"]), "ei": sig(ind["EI_ratio"], 4)})
    check_monotone(rows, "Stage 1")
    ind = g.indicator(1.0)
    return {"label": "Single girder (Stage 1)", "eta_dec": sig(eta_dec), "x_mid": sig(ind["x_mid"], 4),
            "n_el": g.n_el, "rows": rows}


def grillage_models() -> dict:
    gr = Grillage(n_el=N_EL_GRID)
    out = {}
    for name, k in GIRDERS.items():
        eta_dec = eta_decompression(gr.w_pred_fn(k))
        rows, intact, dropped = [], None, []
        for eta in [1.0, *np.linspace(eta_dec, ETA_MIN, N_ETA_GRID)]:
            for relax in (1.0, 0.5):                   # under-relax once before giving up on a point
                ind = gr.indicator(float(eta), k, relax=relax)
                if all(ind["converged"].values()):
                    break
            else:
                dropped.append(sig(eta))               # the page interpolates across it
                continue
            intact = intact or ind
            rows.append({"eta": sig(eta), "w_mm": sig(ind["w_pred_mm"]),
                         "defl_mm": sig(ind["deflection_truck_mm"]["damaged"][k]),
                         "ei": sig(ind["EI_ratio_Gk"], 4),
                         "m_b_kNm": sig(ind["M_B_service_mid_kNm"]["damaged"], 5),
                         "defl_all_mm": sig(ind["deflection_truck_mm"]["damaged"], 5)})
        check_monotone(rows, f"grillage {name}")
        label = "exterior" if name == "G1" else "interior"
        out[name] = {"label": f"Grillage, crack on {name} ({label})", "k": k, "eta_dec": sig(eta_dec),
                     "x_mid": sig(intact["x_mid"], 4), "n_el": N_EL_GRID,
                     "m_b_intact_kNm": sig(intact["M_B_service_mid_kNm"]["intact"], 5),
                     "dropped_eta_not_converged": dropped, "rows": rows}
    return out


def main() -> None:
    t0 = time.perf_counter()
    g = Girder1D()
    data = {
        "meta": {"span_m": g.inp.span, "deflection_limit_mm": sig(g.indicator(1.0)["deflection_limit_mm"]),
                 "gate_px": GATE_PX, "u_per_gsd": U_PER_GSD, "gsds_mm": list(GSDS_MM), "eta_min": ETA_MIN,
                 "source": "scripts/build_demo_data.py"},
        "models": {"single": stage1_model(), **grillage_models()},
    }
    text = "// Generated by scripts/build_demo_data.py; do not edit by hand.\nwindow.DEMO_DATA = "
    OUT.write_text(text + json.dumps(data, separators=(",", ":"), allow_nan=False) + ";\n", encoding="utf-8")
    for name, m in data["models"].items():
        rows = m["rows"]
        print(f"{name}: eta_dec {m['eta_dec']}, w at eta_dec {rows[1]['w_mm']} mm, "
              f"w at eta {rows[-1]['eta']} = {rows[-1]['w_mm']} mm, {len(rows)} rows, "
              f"dropped {m.get('dropped_eta_not_converged', [])}")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1024:.0f} kB) in {time.perf_counter() - t0:.0f} s")


if __name__ == "__main__":
    main()
